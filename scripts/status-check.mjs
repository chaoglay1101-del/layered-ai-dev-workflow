// Consistency check between the ledger and GitHub. Reports only; it never edits either side.
//
// Lists where they disagree:
//   1. a card in the ledger's "Active cards" table is already closed;
//   2. a PR in the ledger's "Assigned" column is already merged or closed (the number should move to "Currently used");
//   3. two open cards labelled agent:ready / agent:running lock overlapping files.
// (The original also compared a to-do document kept in Google Docs. That part is specific to one setup and is not included.)
//
// Usage (needs GITHUB_TOKEN; GITHUB_REPOSITORY is set by Actions):
//   node scripts/status-check.mjs            print the result
//   node scripts/status-check.mjs --locks    print open cards and the files they lock as a Markdown table
//   node scripts/status-check.mjs --report   also update (or open) a pinned issue; closes it when everything agrees
import { readFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { loadConfig, DEFAULTS } from './lib/config.mjs';
import { github } from './lib/github.mjs';
import { cardLocks, findOverlaps } from './lib/locks.mjs';
import { parseLedger } from './lib/ledger.mjs';

export const REPORT_TITLE = 'Status check';
export { findOverlaps, parseLedger };

/* ---------------- pure functions ---------------- */

// items: Map<number, { state, merged, title }> shared by issues and PRs; numbers that could not be looked up are not reported
export function check({ ledger, items, locks }) {
  const problems = [];
  for (const n of ledger.cards) {
    if (items.get(n)?.state === 'closed') problems.push({ kind: 'ledger-card-closed', text: `The ledger lists #${n} under active cards, but it is closed.` });
  }
  for (const { pr, resource } of ledger.assigned) {
    const i = items.get(pr);
    if (!i || i.state !== 'closed') continue;
    problems.push({ kind: 'ledger-pr-done', text: `Ledger "Assigned": PR #${pr} (${resource}) is ${i.merged ? 'merged' : 'closed'}; move the number to "Currently used" or release it.` });
  }
  for (const o of findOverlaps(locks || [])) {
    problems.push({ kind: 'lock-overlap', text: `Cards #${o.a} and #${o.b} lock overlapping files: ${o.files.join(', ')}.` });
  }
  return problems;
}

export function renderLocks(cards, labels = DEFAULTS.labels.lock) {
  if (!cards.length) return `No open cards labelled ${labels.join(' or ')}.\n`;
  const esc = (s) => String(s).replace(/\|/g, '\\|');
  const lines = ['| Card | Labels | Locked files and docs |', '| --- | --- | --- |'];
  for (const c of cards) lines.push(`| #${c.number} ${esc(c.title || '')} | ${esc((c.labels || []).join(', '))} | ${esc(c.locks.join(', ') || '(none listed)')} |`);
  return lines.join('\n') + '\n';
}

export function renderReport(problems) {
  if (!problems.length) return 'Everything agrees';
  return [`${problems.length} mismatch(es):`, '', ...problems.map((p) => `- ${p.text}`)].join('\n');
}

/* ---------------- GitHub ---------------- */

async function openLockCards(gh, config) {
  const byNumber = new Map();
  for (const label of config.labels.lock) {
    for (let page = 1; page <= 5; page++) {
      const batch = await gh('GET', `/issues?labels=${encodeURIComponent(label)}&state=open&per_page=100&page=${page}`);
      for (const i of batch) {
        if (i.pull_request) continue;
        const card = byNumber.get(i.number) || { number: i.number, title: i.title, labels: [], locks: cardLocks(i.body, config.cardHeadings.files) };
        card.labels.push(label);
        byNumber.set(i.number, card);
      }
      if (batch.length < 100) break;
    }
  }
  return [...byNumber.values()].sort((a, b) => a.number - b.number);
}

async function lookup(gh, numbers) {
  const items = new Map();
  for (const n of [...new Set(numbers)]) {
    try {
      const i = await gh('GET', `/issues/${n}`);
      items.set(n, { state: i.state, merged: Boolean(i.pull_request?.merged_at), title: i.title });
    } catch (err) {
      console.error(`Could not look up #${n}: ${err.message}`);
    }
  }
  return items;
}

// One pinned issue: updated when there are problems, commented on and closed when everything agrees
export async function report(gh, problems, config = DEFAULTS, today = new Date().toISOString().slice(0, 10)) {
  const label = config.labels.statusReport;
  const found = await gh('GET', `/issues?labels=${label}&state=all&per_page=10`);
  const existing = found.find((i) => !i.pull_request && i.title === REPORT_TITLE);
  const body = `${renderReport(problems)}\n\n(${today}, generated by scripts/status-check.mjs. It only reports; it changes nothing else.)`;
  if (problems.length) {
    if (!existing) {
      try {
        await gh('GET', `/labels/${label}`);
      } catch {
        await gh('POST', '/labels', { name: label, color: 'fbca04', description: 'Ledger vs GitHub consistency report' });
      }
      const created = await gh('POST', '/issues', { title: REPORT_TITLE, body, labels: [label] });
      return `Opened issue #${created.number}`;
    }
    await gh('PATCH', `/issues/${existing.number}`, { body, state: 'open' });
    return `Updated issue #${existing.number}`;
  }
  if (existing && existing.state === 'open') {
    await gh('POST', `/issues/${existing.number}/comments`, { body: 'Everything agrees' });
    await gh('PATCH', `/issues/${existing.number}`, { state: 'closed', state_reason: 'completed' });
    return `Everything agrees; closed issue #${existing.number}`;
  }
  return 'Everything agrees; nothing to do';
}

async function main() {
  const env = process.env;
  const args = process.argv.slice(2);
  const config = loadConfig();
  if (!env.GITHUB_TOKEN) {
    console.log('GITHUB_TOKEN is not set; skipping the status check.');
    return;
  }
  const gh = github(env.GITHUB_TOKEN, config.repo || env.GITHUB_REPOSITORY);
  const locks = await openLockCards(gh, config);
  if (args.includes('--locks')) {
    process.stdout.write(renderLocks(locks, config.labels.lock));
    return;
  }
  let text;
  try {
    text = readFileSync(config.ledgerPath, 'utf8');
  } catch {
    console.log(`No ${config.ledgerPath}; nothing to compare.`);
    return;
  }
  const ledger = parseLedger(text, config);
  const items = await lookup(gh, [...ledger.cards, ...ledger.assigned.map((a) => a.pr)]);
  const problems = check({ ledger, items, locks });
  console.log(renderReport(problems));
  if (args.includes('--report')) console.log(await report(gh, problems, config));
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((err) => {
    console.error(err.message);
    process.exit(1);
  });
}
